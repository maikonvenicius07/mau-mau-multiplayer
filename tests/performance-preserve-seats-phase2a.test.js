'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'../public/app.js'),'utf8');
const start=app.indexOf('// FASE 2A: reconciliacao dos assentos');
const end=app.indexOf('function renderScore(){',start);
assert(start>=0&&end>start,'Função renderPlayers ausente');
const block=app.slice(start,end);
assert(!block.includes("ring.innerHTML='';"),'renderPlayers não deve limpar todos os assentos');
assert(block.includes('const existing=new Map('),'assentos existentes precisam ser indexados');
assert(block.includes('seat.dataset.cameraPlayerId'),'indexação precisa usar ID do jogador');
assert(block.includes('syncPlayerSeat(previous,d)'),'atualização incremental de fichas ausente');
assert(block.includes('if(!currentIds.has(id))seat.remove()'),'remoção seletiva de jogadores ausente');
assert(block.includes('window.MauCamera?.renderIntoSeats()'),'integração com câmera deve permanecer');
assert(block.includes("existing.querySelector(':scope > .player-card')"),'ficha precisa ser reutilizada');
assert(block.includes("!el.matches('video.camera-video')"),'vídeo deve ficar fora da substituição');
assert(block.includes("oldAvatar.insertBefore(node,oldAvatar.querySelector('video.camera-video'))"),'não substituir raiz do avatar');
console.log('✓ Fase 2A: assentos por ID, avatar e vídeo preservados; atualização seletiva verificada.');
