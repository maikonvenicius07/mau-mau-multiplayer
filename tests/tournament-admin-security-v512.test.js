'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const ui=fs.readFileSync(path.join(root,'public/tournament-ui.js'),'utf8');
const create=server.slice(server.indexOf("app.post('/api/tournaments'"),server.indexOf("app.patch('/api/tournaments/:id'"));
const patch=server.slice(server.indexOf("app.patch('/api/tournaments/:id'"),server.indexOf("app.delete('/api/tournaments/:id'"));
const remove=server.slice(server.indexOf("app.delete('/api/tournaments/:id'"),server.indexOf("app.post('/api/tournaments/:id/draw'"));
assert.match(create,/authFromCookieHeaderVerified/);
assert.match(create,/if\(!session\)/);
assert.doesNotMatch(create,/if\(!tournamentIsAdmin\(session\)\)/);
assert.match(patch,/tournamentCanManage\(session,req.params.id\)/);
assert.match(remove,/tournamentCatalog.delete\(\{id:req.params.id,actor:session.playerKey/);
assert.match(html,/id="tournamentAdminPanel"[^>]*hidden/);
assert.match(html,/id="tournamentAdminDelete"/);
assert.match(ui,/panel.hidden=!canCreate/);
assert.match(ui,/config.canManage/);
assert.match(ui,/tournamentId:config.id/);
assert.match(html,/tournament-ui\.js\?v=51\.3\.1/);
assert.doesNotMatch(ui,/localStorage|sessionStorage/);
console.log('✓ V51.3.1 criar autenticado; gerenciar/excluir restrito ao criador e validado no servidor.');
