'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'public/styles.css'),'utf8');
const js=fs.readFileSync(path.join(root,'public/tournament-ui.js'),'utf8');
assert.match(html,/<div class="landing-links">[\s\S]*id="tournamentOpenHome"[\s\S]*<\/div>/);
assert.equal((html.match(/id="tournamentOpenHome"/g)||[]).length,1);
assert.doesNotMatch(html,/id="tournamentOpenRanking"/);
const rankingStart=html.indexOf('<dialog id="rankingDialog"');
const rankingEnd=html.indexOf('</dialog>',rankingStart);
const ranking=html.slice(rankingStart,rankingEnd);
assert.ok(ranking.includes('id="tournamentResultsInfo"'),'resultados futuros dentro do ranking');
assert.ok(!ranking.includes('tournamentOpenHome'),'inscrições não ficam dentro do ranking');
assert.match(html,/id="tournamentDialog"/);
assert.match(js,/byId\('tournamentOpenHome'\)/);
assert.match(js,/\/api\/tournament\/registration/);
assert.match(css,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
assert.match(css,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)!important/);
assert.match(html,/tournament-ui\.js\?v=51\.4/);
console.log('✓ V51.1.1: acesso aos torneios no início, resultados reservados no Ranking e cadastro preservado.');
